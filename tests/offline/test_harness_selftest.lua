-- Self-test of the fake engine and harness (generic parts only).

test("players: defaults, descending alive IDs, permanent wars", function()
	H.world()
	H.eq(Players[0]:IsHuman(), true)
	H.eq(Players[1]:IsHuman(), false)
	local ids = PlayerManager.GetAliveIDs()
	H.ok(ids[1] > ids[#ids], "GetAliveIDs is descending on purpose")
	H.eq(Players[0]:GetDiplomacy():IsAtWarWith(63), true, "barbarians are at war with everyone")
	H.eq(Players[0]:GetDiplomacy():IsAtWarWith(62), true, "free cities are at war with majors")
	H.eq(Players[1]:GetDiplomacy():IsAtWarWith(4), false)
	H.kill(3)
	H.eq(Players[3]:IsAlive(), false)
	H.eq(PlayerManager.GetAliveMajorsCount(), 3)
end)

test("diplomacy: war and met are symmetric", function()
	H.world()
	H.eq(Players[0]:GetDiplomacy():HasMet(1), false)
	H.war(0, 1)
	H.eq(Players[0]:GetDiplomacy():IsAtWarWith(1), true)
	H.eq(Players[1]:GetDiplomacy():IsAtWarWith(0), true)
	H.eq(Players[1]:GetDiplomacy():HasMet(0), true)
	H.peace(0, 1)
	H.eq(Players[0]:GetDiplomacy():IsAtWarWith(1), false)
	H.eq(Players[0]:GetDiplomacy():HasMet(1), true, "peace does not un-meet")
	H.meet(0, 2)
	H.eq(Players[2]:GetDiplomacy():HasMet(0), true)
end)

