test("events: add, remove, handler errors are captured", function()
	local got = {}
	local function h(x) got[#got + 1] = x end
	GameEvents.Foo.Add(h)
	GameEvents.Foo(1)
	GameEvents.Foo.Remove(h)
	GameEvents.Foo(2)
