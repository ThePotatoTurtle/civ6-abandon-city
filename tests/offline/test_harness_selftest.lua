test("map: odd-r distance, neighbours, wrap", function()
	H.world({ map = { w = 20, h = 10 } })
	H.eq(H.dist(3, 3, 3, 3), 0)
	H.eq(H.dist(3, 2, 4, 2), 1)
	-- even row y=2: neighbours at (x, y+1) and (x-1, y+1); odd row y=3: (x+1, y+1) and (x, y+1)
	H.eq(H.dist(3, 2, 3, 3), 1)
	H.eq(H.dist(3, 2, 2, 3), 1)
	H.eq(H.dist(3, 3, 4, 4), 1)
	H.eq(H.dist(3, 3, 2, 4), 2, "(3,3) to (2,4) is two steps on odd-r")
	H.eq(H.dist(0, 5, 19, 5), 1, "X wraps")
	local ring = Map.GetNeighborPlots(5, 5, 1)
	H.len(ring, 7, "centre plus six neighbours")
	H.ok(ring[1]:GetIndex() > ring[#ring]:GetIndex(), "descending index order")
	H.eq(Map.GetAdjacentPlot(5, 4, DirectionTypes.DIRECTION_EAST):GetX(), 6)
	H.isnil(Map.GetPlot(5, 99))
end)

test("cities: population, ownership, removal", function()
	H.world()
	local cap = H.city(0, 5, 5, 8, { capital = true })
	local c = H.city(0, 12, 5, 6)
	H.city(1, 20, 5, 3)
	H.eq(Players[0]:GetCities():GetCount(), 2)
	H.eq(Players[0]:GetCities():GetCapitalCity(), cap)
	H.eq(CityManager.GetCityAt(12, 5), c)
	H.eq(c:GetPopulation(), 6)
	c:ChangePopulation(-2)
	H.eq(c:GetPopulation(), 4)
	c:ChangePopulation(-10)
	H.eq(c:GetPopulation(), 1, "population floors at 1")
	H.eq(Map.GetPlot(12, 5):GetOwner(), 0)
	H.eq(Map.GetPlot(12, 5):IsCity(), true)
	c:SetProperty("k", 7)
	H.eq(c:GetProperty("k"), 7)
	H.ok(FAKE.RemoveCity(c))
	H.eq(Players[0]:GetCities():GetCount(), 1)
	H.isnil(CityManager.GetCityAt(12, 5))
	H.eq(Map.GetPlot(12, 5):GetOwner(), -1, "plots are released")
	H.len(FAKE.destroyedCities, 1)
end)

test("units: owner, position, combat, kill", function()
	H.world()
	local u = H.unit(0, 4, 4, { combat = 30 })
	local a = H.unit(1, 4, 4, { military = false, combat = 0 })
	H.eq(u:GetOwner(), 0)
	H.eq(u:GetX(), 4)
