test("turns: OnGameTurnStarted fires, order of player turns", function()
	H.world()
	local seen = {}
	GameEvents.OnGameTurnStarted.Add(function(t) seen[#seen + 1] = "start" .. t end)
	GameEvents.OnGameTurnEnded.Add(function(t) seen[#seen + 1] = "end" .. t end)
	GameEvents.PlayerTurnStarted.Add(function(p) seen[#seen + 1] = "p" .. p end)
	local t = H.endTurn()
	H.eq(t, 2)
	H.eq(Game.GetCurrentGameTurn(), 2)
	H.eq(seen[1], "p1", "AI players first, ascending")
	H.contains(seen, "end1")
	H.contains(seen, "start2")
	H.eq(seen[#seen], "p0", "human last")
	H.eq(H.turns(3), 5)
	H.clean()
end)

